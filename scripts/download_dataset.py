"""Fetch the source dataset and cache it as compressed CSV.

The project trains on the **Online Retail II** dataset: real UK online-retail
transactions from 01/12/2009 to 09/12/2011, published by the UCI Machine
Learning Repository (Dr Daqing Chen, London South Bank University) and widely
mirrored on Kaggle.

It is deliberately an external dataset rather than data generated by this
platform. It also carries genuine data-quality problems - missing customer
identifiers, missing descriptions, and cancellation rows with negative
quantities - which is what makes the cleaning stage in dataset/prepare.py real
work rather than a formality.

UCI serves it as a two-sheet .xlsx of roughly a million rows, which is slow to
parse, so this script converts it once to data/raw/online_retail.csv.gz and
everything downstream reads that.

Usage:
    python scripts/download_dataset.py

If the download fails (UCI occasionally rate-limits), download the CSV from
Kaggle by hand and save it as data/raw/online_retail.csv.gz or .csv - the
loader accepts either, and normalises the column names of both the 2009-2011
and the older 2010-2011 release.
"""

from __future__ import annotations

import io
import sys
import time
import urllib.request
import zipfile
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
TARGET = RAW_DIR / "online_retail.csv.gz"

SOURCES = [
    (
        "Online Retail II (2009-2011)",
        "https://archive.ics.uci.edu/static/public/502/online+retail+ii.zip",
    ),
    (
        "Online Retail (2010-2011)",
        "https://archive.ics.uci.edu/static/public/352/online+retail.zip",
    ),
]

USER_AGENT = "Mozilla/5.0 (compatible; ISJ107V-student-project)"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=180) as response:
        return response.read()


def read_spreadsheet(payload: bytes) -> pd.DataFrame:
    """Read every sheet of the archived workbook into one frame."""
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        names = [n for n in archive.namelist() if n.lower().endswith((".xlsx", ".csv"))]
        if not names:
            raise RuntimeError(f"no spreadsheet inside archive: {archive.namelist()}")

        name = names[0]
        print(f"  reading {name} ...", flush=True)
        with archive.open(name) as handle:
            blob = handle.read()

    if name.lower().endswith(".csv"):
        return pd.read_csv(io.BytesIO(blob), encoding="latin-1")

    # Excel: concatenate all sheets, since Online Retail II splits by year.
    sheets = pd.read_excel(io.BytesIO(blob), sheet_name=None, engine="openpyxl")
    print(f"  sheets: {list(sheets)}", flush=True)
    return pd.concat(sheets.values(), ignore_index=True)


def main() -> int:
    RAW_DIR.mkdir(parents=True, exist_ok=True)

    if TARGET.exists():
        size_mb = TARGET.stat().st_size / 1024 / 1024
        print(f"already present: {TARGET.name} ({size_mb:.1f} MB)")
        print("delete it to re-download.")
        return 0

    last_error: Exception | None = None
    for label, url in SOURCES:
        print(f"downloading {label}")
        print(f"  {url}", flush=True)
        started = time.time()
        try:
            payload = fetch(url)
            print(f"  {len(payload) / 1024 / 1024:.1f} MB in "
                  f"{time.time() - started:.0f}s", flush=True)

            frame = read_spreadsheet(payload)
            print(f"  parsed {len(frame):,} rows x {len(frame.columns)} columns",
                  flush=True)

            print(f"  writing {TARGET.name} ...", flush=True)
            frame.to_csv(TARGET, index=False, compression="gzip")

            size_mb = TARGET.stat().st_size / 1024 / 1024
            print(f"done: {TARGET} ({size_mb:.1f} MB)")
            print(f"columns: {list(frame.columns)}")
            return 0

        except Exception as exc:  # noqa: BLE001 - report and try the next mirror
            last_error = exc
            print(f"  failed: {type(exc).__name__}: {exc}", flush=True)

    print()
    print("All sources failed. Download the dataset manually instead:")
    print("  https://www.kaggle.com/datasets/mashlyn/online-retail-ii-uci")
    print(f"and save it as {TARGET} (or as .csv in the same folder).")
    print(f"last error: {last_error}")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
